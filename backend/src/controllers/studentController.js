async function updateStudent(req, res, next) {
  try {
    const { studentId } = req.params;
    const { name, class: className, feeAmount, reminderOptOut, graduatedAt } = req.body;

    const original = await Student.findOne({ schoolId: req.schoolId, studentId }).lean();
    if (!original) {
      const err = new Error('Student not found');
      err.code = 'NOT_FOUND';
      return next(err);
    }

    const update = {};
    if (name !== undefined) update.name = name;
    if (className !== undefined) {
      update.class = className;
      // When the class changes, sync feeAmount from the new class fee structure
      // unless the caller explicitly provides a feeAmount override.
      if (feeAmount === undefined) {
        const feeStructure = await FeeStructure.findOne({ schoolId: req.schoolId, className, isActive: true });
        if (!feeStructure) {
          const err = new Error(`No active fee structure found for class "${className}"`);
          err.code = 'NO_FEE_STRUCTURE';
          err.status = 400;
          return next(err);
        }
        update.feeAmount = feeStructure.feeAmount;
      }
    }
    if (feeAmount !== undefined) {
      const amount = validateDecimalAmount(feeAmount, { minValue: 0.01 });
      if (!amount.ok) return res.status(400).json({ error: amount.error, code: amount.code });
      update.feeAmount = amount.value.toNumber();
    }
    if (reminderOptOut !== undefined) update.reminderOptOut = Boolean(reminderOptOut);
    for (const field of ['paymentConfirmationOptOut', 'disputeUpdateOptOut']) {
      if (req.body[field] === undefined) continue;
      update[field] = req.body[field];
    }
    if (graduatedAt !== undefined) update.graduatedAt = graduatedAt;

    const target = { schoolId: req.schoolId, studentId };
    const student = await Student.findOneAndUpdate(
      { ...target, ...versionFilter(req.expectedVersion) },
      { $set: update, $inc: { __v: 1 } },
      { new: true, runValidators: true },
    );

    if (!student) return staleOrMissing(res, next, Student.findOne(target));

    del(KEYS.student(studentId));

    // Audit log
    if (req.auditContext) {
      await logAudit({
        schoolId: req.schoolId,
        action: 'student_update',
        performedBy: req.auditContext.performedBy,
        targetId: studentId,
        targetType: 'student',
        details: {
          before: { name: original.name, class: original.class, feeAmount: original.feeAmount },
          after: { name: student.name, class: student.class, feeAmount: student.feeAmount },
        },
        result: 'success',
        ipAddress: req.auditContext.ipAddress,
        userAgent: req.auditContext.userAgent,
      });
    }

    withVersion(res, student).json(student);
  } catch (err) {
    if (err.name === 'ValidationError') {
      return res.status(400).json({ error: err.message, code: 'VALIDATION_ERROR' });
    }
    next(err);
  }
}

