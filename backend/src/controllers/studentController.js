async function getPaymentSummary(req, res, next) {
  try {
    const Payment = require('../models/paymentModel');

    const [students, payments] = await Promise.all([
      Student.find({ schoolId: req.schoolId }).lean(),
      Payment.aggregate([
        { $match: { schoolId: req.schoolId, status: 'SUCCESS', isSuspicious: { $ne: true }, deletedAt: null } },
        { $group: { _id: '$studentId', totalPaid: { $sum: '$amount' } } },
      ]),
    ]);

    const paidMap = Object.fromEntries(payments.map(p => [p._id, p.totalPaid]));

    const summary = students.map(s => {
      const totalPaid = parseFloat((paidMap[s.studentId] || 0).toFixed(7));
      const remaining = parseFloat(Math.max(0, s.feeAmount - totalPaid).toFixed(7));
      const status = totalPaid === 0 ? 'unpaid'
        : totalPaid < s.feeAmount ? 'partial'
          : totalPaid > s.feeAmount ? 'overpaid'
            : 'paid';

      return {
        studentId: s.studentId,
        name: s.name,
        class: s.class,
        feeAmount: s.feeAmount,
        totalPaid,
        remaining,
        status,
      };
    });

    const counts = summary.reduce((acc, s) => { acc[s.status] = (acc[s.status] || 0) + 1; return acc; }, {});

    const studentQuota = {
      used: students.length,
      limit: studentLimit(req.school),
      tier: req.school?.subscriptionTier || 'free',
      upgrade_url: upgradeUrl,
    };
    res.json({ total: students.length, counts, students: summary, studentQuota });
  } catch (err) {
    next(err);
  }
}

// ── Helpers for bulk import ──────────────────────────────────────────────────

const CSV_MAX_SIZE_BYTES = parseInt(process.env.CSV_MAX_SIZE_BYTES, 10) || 5 * 1024 * 1024; // 5 MB
const CSV_MAX_ROWS = parseInt(process.env.CSV_MAX_ROWS, 10) || 10000;
const CSV_MAX_COLUMNS = parseInt(process.env.CSV_MAX_COLUMNS, 10) || 20;
const BULK_IMPORT_MAX_FAILURES = parseInt(process.env.BULK_IMPORT_MAX_FAILURES, 10) || 100;

function parseCsvBuffer(buffer) {
  return new Promise((resolve, reject) => {
    const rows = [];
    const stream = Readable.from(buffer);
    let lineNumber = 1;
    stream
      .pipe(csv())
      .on('data', (row) => {
        lineNumber++;
        if (rows.length >= CSV_MAX_ROWS) {
          stream.destroy();
          const err = new Error(`CSV exceeds maximum row limit of ${CSV_MAX_ROWS}`);
          err.code = 'CSV_TOO_MANY_ROWS';
          err.status = 400;
          return reject(err);
        }
        if (Object.keys(row).length > CSV_MAX_COLUMNS) {
          stream.destroy();
          const err = new Error(`Row ${lineNumber} has too many columns. Max is ${CSV_MAX_COLUMNS}`);
          err.code = 'CSV_INVALID_FORMAT';
          err.status = 400;
          return reject(err);
        }
        rows.push(row);
      })
      .on('end', () => resolve(rows))
      .on('error', (err) => reject(err));
  });
}

const STUDENT_ID_RE = /^[A-Za-z0-9_-]{3,20}$/;

function validateStudentRow(row) {
  const errors = [];
  const fieldErrors = [];

  // studentId: required, must match pattern
  if (!row.studentId || typeof row.studentId !== 'string' || !row.studentId.trim()) {
    errors.push('studentId is required');
    fieldErrors.push({ field: 'studentId', error: 'studentId is required' });
  } else if (!STUDENT_ID_RE.test(row.studentId.trim())) {
    errors.push('studentId must be 3–20 alphanumeric characters (letters, digits, _ or -)');
    fieldErrors.push({ field: 'studentId', error: 'studentId must be 3–20 alphanumeric characters (letters, digits, _ or -)' });
  }

  // name: required, non-empty string
  if (!row.name || typeof row.name !== 'string' || !row.name.trim()) {
    errors.push('name is required');
    fieldErrors.push({ field: 'name', error: 'name is required' });
  }

  // class: required, non-empty string
  if (!row.class || typeof row.class !== 'string' || !row.class.trim()) {
    errors.push('class is required');
    fieldErrors.push({ field: 'class', error: 'class is required' });
  }

  // feeAmount: optional, but if provided must be a positive number
  if (row.feeAmount != null && row.feeAmount !== '') {
    const amount = validateDecimalAmount(row.feeAmount, { minValue: 0.01 });
    if (!amount.ok) {
      errors.push(amount.error);
      fieldErrors.push({ field: 'feeAmount', error: amount.error });
    }
  }

  return { errors, fieldErrors };
}

// POST /api/students/bulk
async function bulkImportStudents(req, res, next) {
  try {
    const { schoolId } = req;
    if (req.csvFileId) {
      if (!req.csvRowCount) {
        const mongoose = require('mongoose');
        const bucket = new mongoose.mongo.GridFSBucket(mongoose.connection.db, { bucketName: 'studentImports' });
        await bucket.delete(req.csvFileId).catch(() => {});
        return res.status(400).json({ error: 'No student records found in input', code: 'VALIDATION_ERROR' });
      }

      const ImportJob = require('../models/importJobModel');
      const { enqueueStudentImport } = require('../queue/studentImportQueue');
      const jobId = require('crypto').randomUUID();
      await ImportJob.create({ jobId, schoolId, totalRows: req.csvRowCount, status: 'pending' });

      try {
        await enqueueStudentImport({ jobId, schoolId, fileId: String(req.csvFileId) });
      } catch (queueError) {
        await ImportJob.updateOne({ jobId }, { status: 'failed', completedAt: new Date(), failureReason: queueError.message });
        const mongoose = require('mongoose');
        const bucket = new mongoose.mongo.GridFSBucket(mongoose.connection.db, { bucketName: 'studentImports' });
        await bucket.delete(req.csvFileId).catch(() => {});
        return res.status(503).json({ error: 'Student import queue is unavailable', code: 'QUEUE_UNAVAILABLE' });
      }

      if (req.auditContext) {
        await logAudit({
          schoolId,
          action: 'student_bulk_import',
          performedBy: req.auditContext.performedBy,
          targetId: jobId,
          targetType: 'student_import_job',
          details: { total: req.csvRowCount, status: 'pending' },
          result: 'success',
          ipAddress: req.auditContext.ipAddress,
          userAgent: req.auditContext.userAgent,
        });
      }

      return res.status(202).json({ jobId, status: 'pending', totalRows: req.csvRowCount });
    }

    let rows;

    if (req.parsedRows) {
      rows = req.parsedRows;
    } else if (req.body && Array.isArray(req.body.students)) {
      rows = req.body.students;
    } else {
      return res.status(400).json({
        error: 'Provide a CSV file (field "file") or a JSON body with { "students": [...] }',
        code: 'VALIDATION_ERROR',
      });
    }

    if (rows.length === 0) {
      return res.status(400).json({ error: 'No student records found in input', code: 'VALIDATION_ERROR' });
    }

    const results = { total: rows.length, created: 0, failed: 0, details: [] };

    const usage = await quotaUsage(req.school);
    const quotaRemaining = usage.limit === null ? Infinity : usage.limit - usage.used;

    // Pre-fetch fee structures for all unique class names (one query per unique class, not per row)
    const uniqueClasses = [...new Set(rows.map(r => r.class?.trim()).filter(Boolean))];
    const feeStructureMap = {};
    if (uniqueClasses.length > 0) {
      const feeStructures = await FeeStructure.find({
        schoolId,
        className: { $in: uniqueClasses },
        isActive: true,
      }).lean();
      feeStructures.forEach(fs => {
        feeStructureMap[fs.className] = fs.feeAmount;
      });
    }

    // Validate all rows first
    const validatedRows = [];
    let quotaExceededAt = -1;
    for (let i = 0; i < rows.length; i++) {
      const row = rows[i];
      const { errors: validationErrors, fieldErrors } = validateStudentRow(row);

      if (validationErrors.length > 0) {
        results.failed++;
        if (results.details.length < BULK_IMPORT_MAX_FAILURES) {
          results.details.push({
            row: i + 2,
            studentId: row.studentId || null,
            error: validationErrors[0],
            field: fieldErrors[0]?.field || null,
            code: 'VALIDATION_ERROR',
          });
        }
        continue;
      }

      // Check quota before adding to validatedRows
      if (quotaExceededAt === -1 && validatedRows.length >= quotaRemaining) {
        quotaExceededAt = i;
      }

      if (quotaExceededAt !== -1 && i >= quotaExceededAt) {
        results.failed++;
        if (results.details.length < BULK_IMPORT_MAX_FAILURES) {
          results.details.push({
            row: i + 2,
            studentId: row.studentId,
            error: `School has reached maximum student quota of ${usage.limit}`,
            code: 'STUDENT_QUOTA_EXCEEDED',
          });
        }
        continue;
      }

      let assignedFee = row.feeAmount != null && row.feeAmount !== '' ? Number(row.feeAmount) : null;
      if (assignedFee == null && row.class) {
        assignedFee = feeStructureMap[row.class.trim()];
      }

      if (assignedFee == null) {
        results.failed++;
        if (results.details.length < BULK_IMPORT_MAX_FAILURES) {
          results.details.push({
            row: i + 2,
            studentId: row.studentId,
            error: `No feeAmount provided and no fee structure found for class "${row.class}"`,
            field: 'class',
            code: 'FEE_STRUCTURE_NOT_FOUND',
          });
        }
        continue;
      }

      const rawParentEmail = row.parentEmail ? row.parentEmail.trim().toLowerCase() : null;
      const rawParentPhone = row.parentPhone ? row.parentPhone.trim() : null;
      validatedRows.push({
        index: i,
        schoolId,
        studentId: row.studentId.trim(),
        name: row.name.trim(),
        class: row.class.trim(),
        feeAmount: assignedFee,
        // insertMany() below bypasses the model's pre('save') encryption
        // hook (issue #1480), so parentEmail/parentPhone are encrypted here.
        parentEmail: encryptStudentPii(rawParentEmail),
        parentPhone: encryptStudentPii(rawParentPhone),
        parentEmailHash: hashParentEmail(rawParentEmail),
      });
    }

    // Process validated rows in chunks using insertMany with ordered: false
    const CHUNK_SIZE = 500;
    for (let i = 0; i < validatedRows.length; i += CHUNK_SIZE) {
      const chunk = validatedRows.slice(i, i + CHUNK_SIZE);
      try {
        const inserted = await Student.insertMany(chunk, { ordered: false });
        results.created += inserted.length;
        inserted.forEach(student => {
          if (results.details.length < BULK_IMPORT_MAX_FAILURES) {
            const originalRow = chunk.find(r => r.studentId === student.studentId);
            results.details.push({
              row: originalRow.index + 2,
              studentId: student.studentId,
              status: 'created',
              _id: student._id,
            });
          }
        });
      } catch (err) {
        // insertMany with ordered: false throws a BulkWriteError with insertedDocs and writeErrors
        if (err.insertedDocs) {
          results.created += err.insertedDocs.length;
          err.insertedDocs.forEach(student => {
            if (results.details.length < BULK_IMPORT_MAX_FAILURES) {
              const originalRow = chunk.find(r => r.studentId === student.studentId);
              results.details.push({
                row: originalRow.index + 2,
                studentId: student.studentId,
                status: 'created',
                _id: student._id,
              });
            }
          });
        }
        if (err.writeErrors) {
          err.writeErrors.forEach(writeErr => {
            if (results.details.length < BULK_IMPORT_MAX_FAILURES) {
              const failedRow = chunk[writeErr.index];
              results.failed++;
              const message = writeErr.err.code === 11000
                ? 'Student ID already exists in this school'
                : writeErr.err.message;
              results.details.push({
                row: failedRow.index + 2,
                studentId: failedRow.studentId,
                error: message,
                code: writeErr.err.code === 11000 ? 'DUPLICATE_STUDENT_ID' : 'INSERT_ERROR',
              });
            }
          });
        }
      }
    }

    del(KEYS.studentsAll());

    // Audit log for bulk import
    if (req.auditContext) {
      await logAudit({
        schoolId,
        action: 'student_bulk_import',
        performedBy: req.auditContext.performedBy,
        targetId: 'bulk',
        targetType: 'student',
        details: { total: results.total, created: results.created, failed: results.failed },
        result: results.created > 0 ? 'success' : 'failure',
        ipAddress: req.auditContext.ipAddress,
        userAgent: req.auditContext.userAgent,
      });
    }

    res.status(results.failed === results.total ? 400 : 201).json(results);
  } catch (err) {
    if (err.code === 'CSV_TOO_MANY_ROWS') {
      return res.status(400).json({ error: err.message, code: err.code });
    }
    next(err);
  }
}

